#!/usr/bin/env python3
"""
validate-topics-registry.py — every live study is reachable, every listing resolves.

`data/books-content.json` is the single source of truth for what the site
offers: `books[]` drives the per-book cards on /studies/, and `topical[]` drives
the Topical Studies strip. A study page that is in neither is live on the server
and reachable by nobody.

That is not hypothetical. `/topics/index.html` looks like a second registry —
it carries a hand-maintained grid of topic cards — but it has redirected to
/studies/ since the Studies reshape, so its cards render for nobody. Two people
in a row read it as authoritative and "registered" a study by adding a card to
it. This check exists so the mistake announces itself.

    python3 scripts/validate-topics-registry.py

Checks:
  * every LIVE page at src/pages/topics/<slug>/index.astro is reachable from
    books-content.json — via topical[] or via any books[] tier url;
  * every topical[] entry resolves to a real page and carries a label;
  * every books[] tier marked exists:true resolves to a real page;
  * slugs in topical[] are unique.

Exit non-zero on any failure.
"""
import json, os, re, sys, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGES = os.path.join(ROOT, 'src/pages')
fails = []

def check(ok, msg):
    print(('  ok  ' if ok else 'FAIL  ') + msg)
    if not ok:
        fails.append(msg)

def is_redirect(path):
    """A retired page kept only so old links resolve."""
    try:
        return 'http-equiv="refresh"' in open(path, encoding='utf-8').read()
    except OSError:
        return False

def page_exists(url):
    """Does a books-content url map to a page this build will emit?"""
    url = url.split('#', 1)[0].split('?', 1)[0].strip('/')
    if not url:
        return False
    cands = []
    if url.endswith('.html'):
        cands.append(os.path.join(PAGES, url[:-5] + '.astro'))
        cands.append(os.path.join(PAGES, url[:-10] + 'index.astro') if url.endswith('/index.html') else '')
    else:
        cands.append(os.path.join(PAGES, url, 'index.astro'))
        cands.append(os.path.join(PAGES, url + '.astro'))
    # book pages are generated by the [book] dynamic route, not by a file per book
    if re.match(r'^topics/[^/]+/(commentary|index|deep-dive)\.html$', url):
        cands.append(os.path.join(PAGES, 'topics/[book]',
                                  os.path.basename(url)[:-5] + '.astro'))
    return any(c and os.path.exists(c) for c in cands)

def main():
    data = json.load(open(os.path.join(ROOT, 'data/books-content.json'), encoding='utf-8'))
    topical = data.get('topical') or []
    books = data.get('books') or {}

    slugs = [t.get('slug') for t in topical]
    check(len(slugs) == len(set(slugs)), f'topical slugs are unique ({len(slugs)} entries)')

    reachable = set()
    for t in topical:
        url = (t.get('url') or '').strip('/')
        check(bool(t.get('label')), f'topical/{t.get("slug")}: has a label')
        check(page_exists(t.get('url') or ''),
              f'topical/{t.get("slug")}: url resolves to a page ({t.get("url")})')
        m = re.match(r'^topics/([^/]+)', url)
        if m:
            reachable.add(m.group(1))

    for bid, tiers in books.items():
        for tier, info in (tiers or {}).items():
            if not isinstance(info, dict) or not info.get('exists'):
                continue
            url = (info.get('url') or '').strip('/')
            check(page_exists(info.get('url') or ''),
                  f'books/{bid}/{tier}: url resolves to a page ({info.get("url")})')
            m = re.match(r'^topics/([^/]+)', url)
            if m:
                reachable.add(m.group(1))

    for idx in sorted(glob.glob(os.path.join(PAGES, 'topics/*/index.astro'))):
        slug = os.path.basename(os.path.dirname(idx))
        if slug.startswith('[') or slug.startswith('_'):
            continue
        if is_redirect(idx):
            continue
        check(slug in reachable,
              f'topics/{slug}: listed in books-content.json, so a reader can find it')

    print()
    if fails:
        print(f'{len(fails)} FAILURE(S)')
        print('A live study that is in neither books[] nor topical[] is reachable '
              'by nobody. Note that /topics/index.html is a REDIRECT — adding a '
              'card there registers nothing.')
        return 1
    print('topics registry is consistent')
    return 0

if __name__ == '__main__':
    sys.exit(main())
